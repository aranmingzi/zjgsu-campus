// 注意：要放在 courses 展开之前 —— 下面生成课程时就要用它推断类型了
const COURSE_TYPES = ['专业必修', '专业选修', '通识课', '体育课', '思政课'];
const DEFAULT_COURSE_TYPE = '专业必修';

// 展开为 courses 数组（自动分配 id / 学分 / 描述）
const courses = [];
let _cid = 0;
Object.keys(rawCourses).forEach((college) => {
  const majors = rawCourses[college];
  Object.keys(majors).forEach((major) => {
    (majors[major] || []).forEach((name) => {
      if (!name) return;
      _cid += 1;
      courses.push({
        id: 'c' + _cid,
        name: name,
        college: college,
        major: major,
        credit: 3,
        tags: [],
        ctype: guessCourseType(name),
        description: '属于' + major + '（' + college + '）的核心课程之一。'
      });
    });
  });
});

// 课程类型推断（专业必修 / 专业选修 / 通识课 / 体育课 / 思政课）。
// 官网课程数据不带「课程性质」，只能按课名识别 —— 五类的判据都用强特征词，
// 宁可把拿不准的归进「专业必修」（官网专业介绍里的课本来就以专业核心课为主），
// 也不要瞎猜。同学自建课程与老用户的本地课程缓存都用这一个函数补类型，
// 保证列表页「按类型筛选」对全部课程可用。
//
// 说清楚一件事：官方课目录这 900 门基本都是各专业的专业课，按名推断出来
// 98% 是「专业必修」—— 体育课 / 思政课 / 通识课这类全校公共课不在目录里。
// 所以「添加课程」页让同学自己挑类型，挑了就以他挑的为准（见 pickCourseType）。
function guessCourseType(name) {
  const t = String(name || '');
  if (/体育|球类|田径|游泳|武术|太极|健美操|瑜伽/.test(t)) return '体育课';
  if (/思想政治|思政|马克思主义|毛泽|习近平|新时代|形势与政策|思想道德|法律基础|中国近现代史|纲要|原理概论/.test(t)) return '思政课';
  // 通识：军事、心理、职业、美育、语言文字这一类面向全校的素养课
  if (/军事|国防|安全教育|心理健康|职业生涯|就业指导|创新创业|劳动|通识|美育|艺术|音乐|影视|戏剧|书法|美术|大学语文|应用文写作|演讲与口才|沟通|礼仪|生态文明|健康教育|心理/.test(t)) return '通识课';
  if (/任选|公选|选修/.test(t)) return '专业选修';
  return DEFAULT_COURSE_TYPE;
}

// 同学手挑的类型为准，挑不出来（没挑 / 传了怪值）才按课名推断
function pickCourseType(want, name) {
  const w = String(want || '').trim();
  if (COURSE_TYPES.indexOf(w) >= 0) return w;
  return guessCourseType(name);
}

